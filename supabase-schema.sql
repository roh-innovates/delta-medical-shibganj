-- =====================================================================
-- RPC 1: Public Booking (Atomic Lock + Duplicate Guard + Anti-Spam Rate Limits)
-- Matches duplicates on (normalized phone + patient_name + doctor + date)
-- where status <> 'Cancelled' so double-taps return the existing SL-XX while
-- parents can still book multiple family members using one phone.
-- Rate limits protect against bot/spam floods:
--   • Max 5 bookings per phone per 10 minutes
--   • Max 10 active bookings per phone per 24 hours
--   • Global burst circuit breaker: max 150 bookings per minute
-- =====================================================================

drop function if exists public.create_public_booking(text, text, text, text, date);

create or replace function public.create_public_booking(
  p_patient_name text,
  p_patient_phone text,
  p_doctor_name text,
  p_department text,
  p_appointment_date date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
  v_phone text;
  v_doctor text;
  v_dept text;
  v_dhaka_today date;
  v_existing_serial integer;
  v_existing_status text;
  v_recent_phone_count integer;
  v_daily_phone_count integer;
  v_global_minute_count integer;
  v_next_serial integer;
begin
  v_name := trim(coalesce(p_patient_name, ''));
  v_doctor := trim(coalesce(p_doctor_name, ''));
  v_dept := trim(coalesce(p_department, ''));
  v_dhaka_today := (now() at time zone 'Asia/Dhaka')::date;
  v_phone := public.normalize_bd_phone(p_patient_phone);

  if length(v_name) < 2 or length(v_name) > 120 then
    raise exception 'Patient name must be between 2 and 120 characters';
  end if;
  if v_phone !~ '^01[3-9][0-9]{8}$' then
    raise exception 'Please enter a valid 11-digit Bangladeshi mobile number';
  end if;
  if v_doctor = '' or v_dept = '' or p_appointment_date is null then
    raise exception 'Doctor, department, and appointment date are required';
  end if;
  if length(v_doctor) > 160 or length(v_dept) > 160 then
    raise exception 'Doctor or department name is too long';
  end if;
  if p_appointment_date < v_dhaka_today then
    raise exception 'Appointment date cannot be in the past';
  end if;

  -- Lock hierarchy Level 1 (phone) -> Level 2 (doctor|date) prevents both
  -- parallel rate-limit bypass and concurrent serial number collisions.
  perform pg_advisory_xact_lock(hashtext('phone|' || v_phone));
  perform pg_advisory_xact_lock(
    hashtext(lower(v_doctor) || '|' || p_appointment_date::text)
  );

  -- Family-friendly duplicate guard using indexed patient_phone_norm (<1ms B-tree lookup)
  select a.serial_no, a.status
    into v_existing_serial, v_existing_status
  from public.appointments a
  where a.patient_phone_norm = v_phone
    and a.appointment_date = p_appointment_date
    and lower(trim(a.patient_name)) = lower(v_name)
    and lower(trim(a.doctor_name)) = lower(v_doctor)
    and a.status <> 'Cancelled'
  order by a.created_at asc
  limit 1;

  if found then
    return jsonb_build_object(
      'serial_no', coalesce(v_existing_serial, 1),
      'is_duplicate', true,
      'status', coalesce(v_existing_status, 'Pending')
    );
  end if;

  -- Anti-spam guard 1: max 5 bookings per phone in 10 minutes (indexed)
  select count(*)
    into v_recent_phone_count
  from public.appointments a
  where a.patient_phone_norm = v_phone
    and a.created_at >= now() - interval '10 minutes';

  if v_recent_phone_count >= 5 then
    raise exception 'অতিরিক্ত সিরিয়াল অনুরোধ: এই নম্বর থেকে ১০ মিনিটে সর্বোচ্চ ৫টি সিরিয়াল বুক করা যায়। অনুগ্রহ করে কিছুক্ষণ পর চেষ্টা করুন অথবা ০১৭২৪-৩৬৩৮৩৮ নম্বরে কল করুন।';
  end if;

  -- Anti-spam guard 2: max 10 active bookings per phone in 24 hours (indexed)
  select count(*)
    into v_daily_phone_count
  from public.appointments a
  where a.patient_phone_norm = v_phone
    and a.created_at >= now() - interval '24 hours'
    and a.status <> 'Cancelled';

  if v_daily_phone_count >= 10 then
    raise exception 'দৈনিক সীমা অতিক্রম: এই নম্বর থেকে ২৪ ঘণ্টায় সর্বোচ্চ ১০টি সিরিয়াল বুক করা যায়। অতিরিক্ত সিরিয়ালের জন্য ০১৭২৪-৩৬৩৮৩৮ নম্বরে কল করুন।';
  end if;

  -- Anti-spam guard 3: global bot-flood circuit breaker (150 bookings / minute)
  select count(*)
    into v_global_minute_count
  from public.appointments a
  where a.created_at >= now() - interval '1 minute';

  if v_global_minute_count >= 150 then
    raise exception 'সার্ভারে অতিরিক্ত চাপ রয়েছে। অনুগ্রহ করে ১ মিনিট পর আবার চেষ্টা করুন অথবা ০১৭২৪-৩৬৩৮৩৮ নম্বরে কল করুন।';
  end if;

  select coalesce(max(serial_no), 0) + 1
    into v_next_serial
  from public.appointments
  where lower(trim(doctor_name)) = lower(v_doctor)
    and appointment_date = p_appointment_date;

  insert into public.appointments (
    serial_no,
    patient_name,
    patient_phone,
    patient_phone_norm,
    doctor_name,
    department,
    appointment_date,
    status
  ) values (
    v_next_serial,
    v_name,
    v_phone,
    v_phone,
    v_doctor,
    v_dept,
    p_appointment_date,
    'Pending'
  );

  return jsonb_build_object(
    'serial_no', v_next_serial,
    'is_duplicate', false,
    'status', 'Pending'
  );
end;
$$;

revoke all on function public.create_public_booking(text, text, text, text, date) from public;
grant execute on function public.create_public_booking(text, text, text, text, date) to anon, authenticated;

-- =====================================================================
-- RPC 2: Admin Walk-In / Phone Booking (Shares Same Atomic Serial Lock)
-- Authenticated reception staff only.
-- =====================================================================

drop function if exists public.create_admin_booking(text, text, text, text, date, text, text);

create or replace function public.create_admin_booking(
  p_patient_name text,
  p_patient_phone text,
  p_doctor_name text,
  p_department text,
  p_appointment_date date,
  p_status text default 'Confirmed',
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
  v_phone text;
  v_doctor text;
  v_dept text;
  v_status text;
  v_next_serial integer;
  v_new_id text;
begin
  if auth.role() <> 'authenticated' then
    raise exception 'Unauthorized';
  end if;

  v_name := trim(coalesce(p_patient_name, ''));
  v_doctor := trim(coalesce(p_doctor_name, ''));
  v_dept := trim(coalesce(p_department, ''));
  v_status := case
    when p_status in ('Pending', 'Confirmed', 'Completed', 'Cancelled') then p_status
    else 'Pending'
  end;

  v_phone := public.normalize_bd_phone(p_patient_phone);

  if length(v_name) < 2 then
    raise exception 'Patient name is required';
  end if;
  if length(v_phone) < 7 then
    raise exception 'Valid phone number is required';
  end if;
  if v_doctor = '' or v_dept = '' or p_appointment_date is null then
    raise exception 'Doctor, department, and appointment date are required';
  end if;

  -- Shares the exact same advisory lock key as create_public_booking
  perform pg_advisory_xact_lock(
    hashtext(lower(v_doctor) || '|' || p_appointment_date::text)
  );

  select coalesce(max(serial_no), 0) + 1
    into v_next_serial
  from public.appointments
  where lower(trim(doctor_name)) = lower(v_doctor)
    and appointment_date = p_appointment_date;

  insert into public.appointments (
    serial_no,
    patient_name,
    patient_phone,
    patient_phone_norm,
    doctor_name,
    department,
    appointment_date,
    status,
    notes
  ) values (
    v_next_serial,
    v_name,
    v_phone,
    v_phone,
    v_doctor,
    v_dept,
    p_appointment_date,
    v_status,
    nullif(trim(coalesce(p_notes, '')), '')
  )
  returning id::text into v_new_id;

  return jsonb_build_object(
    'id', v_new_id,
    'serial_no', v_next_serial
  );
end;
$$;

revoke all on function public.create_admin_booking(text, text, text, text, date, text, text) from public;
grant execute on function public.create_admin_booking(text, text, text, text, date, text, text) to authenticated;

-- =====================================================================
-- RPC 3: Privacy-Safe Patient "Check My Serial" Lookup
-- Requires exact 11-digit Bangladeshi mobile number; never exposes
-- internal notes, row IDs, or other patients' records.
-- =====================================================================

drop function if exists public.lookup_patient_serials(text, date);

create or replace function public.lookup_patient_serials(
  p_patient_phone text,
  p_appointment_date date default null
)
returns table (
  serial_no integer,
  patient_name text,
  patient_phone text,
  doctor_name text,
  department text,
  appointment_date date,
  status text,
  doctor_name_bn text,
  room_no text,
  current_serial integer,
  queue_updated_date date
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_phone text;
  v_dhaka_today date;
begin
  v_phone := public.normalize_bd_phone(p_patient_phone);

  -- Require exact 11-digit BD mobile number to prevent partial-phone scraping
  if v_phone !~ '^01[3-9][0-9]{8}$' then
    return;
  end if;

  v_dhaka_today := (now() at time zone 'Asia/Dhaka')::date;

  return query
  select
    a.serial_no,
    a.patient_name,
    a.patient_phone,
    a.doctor_name,
    a.department,
    a.appointment_date,
    a.status,
    d.name_bn as doctor_name_bn,
    d.room_no,
    coalesce(d.current_serial, 0) as current_serial,
    d.queue_updated_date
  from public.appointments a
  left join lateral (
    select doc.name_bn, doc.room_no, doc.current_serial, doc.queue_updated_date
    from public.doctors doc
    where lower(trim(doc.name_en)) = lower(trim(a.doctor_name))
       or trim(doc.name_bn) = trim(a.doctor_name)
    order by doc.is_active desc, doc.display_order asc nulls last, doc.id asc
    limit 1
  ) d on true
  where a.patient_phone_norm = v_phone
    and (
      (p_appointment_date is not null and a.appointment_date = p_appointment_date)
      or (p_appointment_date is null and a.appointment_date >= v_dhaka_today)
    )
  order by a.appointment_date asc, a.created_at desc
  limit 10;
end;
$$;

revoke all on function public.lookup_patient_serials(text, date) from public;
grant execute on function public.lookup_patient_serials(text, date) to anon, authenticated;

